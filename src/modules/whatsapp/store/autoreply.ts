export const AWAY_SCHEDULE_KEYWORD = "__AWAY_SCHEDULE__";

interface ActiveFlowState {
    stepId: string;
    vars: Record<string, string>;
    updatedAt: number;
}

const activeFlowMap = new Map<string, ActiveFlowState>();
const flowCooldownMap = new Map<string, number>();

interface AwayScheduleConfig {
    enabled: boolean;
    startTime: string; // "07:30"
    endTime: string;   // "18:00"
    workDays: number[]; // [1, 2, 3, 4, 5] (0=Sun .. 6=Sat)
    message: string;
    cooldownMinutes: number;
}

// Cooldown map: `${sessionId}:${remoteJid}` -> timestamp (ms)
const awayCooldownMap = new Map<string, number>();

// Human handoff pause: `${sessionId}:${remoteJid}` -> pauseUntilTimestamp (ms)
const humanPauseMap = new Map<string, number>();
// Track message key IDs generated by the bot itself so the bot doesn't trigger operator pause
const botSentKeys = new Set<string>();

const STATE_FILE = path.join(process.cwd(), "data", "autoreply-state.json");

// Helper to persist flow state & pauses to disk
let saveTimeout: NodeJS.Timeout | null = null;
export function persistAutoReplyState() {
    if (saveTimeout) clearTimeout(saveTimeout);
    saveTimeout = setTimeout(() => {
        try {
            const data = {
                activeFlows: Array.from(activeFlowMap.entries()).filter(([_, v]) => v && v.updatedAt && Date.now() - v.updatedAt < 24 * 60 * 60 * 1000),
                humanPauses: Array.from(humanPauseMap.entries()).filter(([_, until]) => until > Date.now()),
                flowCooldowns: Array.from(flowCooldownMap.entries()).filter(([_, until]) => until > Date.now()),
                awayCooldowns: Array.from(awayCooldownMap.entries()).filter(([_, until]) => until > Date.now()),
            };
            const dir = path.dirname(STATE_FILE);
            if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
            fs.writeFileSync(STATE_FILE, JSON.stringify(data, null, 2), "utf-8");
        } catch (err) {
            logger.error("AutoReply", "Falha ao salvar estado do robô no disco:", err);
        }
    }, 500);
}

// Load state on startup
export function loadAutoReplyState() {
    try {
        if (!fs.existsSync(STATE_FILE)) return;
        const raw = fs.readFileSync(STATE_FILE, "utf-8");
        const data = JSON.parse(raw);
        if (Array.isArray(data.activeFlows)) {
            for (const [k, v] of data.activeFlows) {
                if (v && v.updatedAt && Date.now() - v.updatedAt < 24 * 60 * 60 * 1000) {
                    activeFlowMap.set(k, v);
                }
            }
        }
        if (Array.isArray(data.humanPauses)) {
            for (const [k, v] of data.humanPauses) {
                if (typeof v === "number" && v > Date.now()) {
                    humanPauseMap.set(k, v);
                }
            }
        }
        if (Array.isArray(data.flowCooldowns)) {
            for (const [k, v] of data.flowCooldowns) {
                if (typeof v === "number" && v > Date.now()) {
                    flowCooldownMap.set(k, v);
                }
            }
        }
        if (Array.isArray(data.awayCooldowns)) {
            for (const [k, v] of data.awayCooldowns) {
                if (typeof v === "number" && v > Date.now()) {
                    awayCooldownMap.set(k, v);
                }
            }
        }
        logger.info("AutoReply", `Estado de fluxos restaurado: ${activeFlowMap.size} fluxos ativos, ${humanPauseMap.size} pausas`);
    } catch (err) {
        logger.error("AutoReply", "Falha ao carregar estado do robô do disco:", err);
    }
}

// Carrega estado imediatamente na inicialização
loadAutoReplyState();

function setActiveFlow(key: string, state: ActiveFlowState) {
    activeFlowMap.set(key, state);
    persistAutoReplyState();
}

function deleteActiveFlow(key: string) {
    activeFlowMap.delete(key);
    persistAutoReplyState();
}

/**
 * Pausa o robô para uma conversa específica por X minutos (padrão: 15 min).
 */
export function pauseBotForChat(sessionId: string, remoteJid: string, durationMinutes = 15) {
    humanPauseMap.set(`${sessionId}:${remoteJid}`, Date.now() + durationMinutes * 60 * 1000);
    persistAutoReplyState();
}

/**
 * Reativa o robô para uma conversa específica imediatamente.
 */
export function unpauseBotForChat(sessionId: string, remoteJid: string) {
    humanPauseMap.delete(`${sessionId}:${remoteJid}`);
    persistAutoReplyState();
}

/**
 * Verifica se o robô está pausado para esta conversa.
 */
export function resetFlowAndPausesForSession(sessionId: string) {
    const prefix = `${sessionId}:`;
    for (const k of Array.from(humanPauseMap.keys())) {
        if (k.startsWith(prefix)) humanPauseMap.delete(k);
    }
    for (const k of Array.from(activeFlowMap.keys())) {
        if (k.startsWith(prefix)) activeFlowMap.delete(k);
    }
    for (const k of Array.from(flowCooldownMap.keys())) {
        if (k.startsWith(prefix)) flowCooldownMap.delete(k);
    }
    for (const k of Array.from(awayCooldownMap.keys())) {
        if (k.startsWith(prefix)) awayCooldownMap.delete(k);
    }
    persistAutoReplyState();
    logger.info("AutoReply", `Pausas e estados de fluxo resetados para a sessão ${sessionId}`);
}

export function isBotPausedForChat(sessionId: string, remoteJid: string): boolean {
    const until = humanPauseMap.get(`${sessionId}:${remoteJid}`);
    if (!until) return false;
    if (Date.now() >= until) {
        humanPauseMap.delete(`${sessionId}:${remoteJid}`);
        return false;
    }
    return true;
}

/**
 * Retorna os milissegundos restantes da pausa do robô (0 se não estiver pausado).
 */
export function getBotPauseRemainingMs(sessionId: string, remoteJid: string): number {
    const until = humanPauseMap.get(`${sessionId}:${remoteJid}`);
    if (!until) return 0;
    const diff = until - Date.now();
    if (diff <= 0) {
        humanPauseMap.delete(`${sessionId}:${remoteJid}`);
        return 0;
    }
    return diff;
}

function getNowInSaoPaulo(): { dayOfWeek: number; timeHHMM: string; greeting: string } {
    const now = new Date();
    const parts = new Intl.DateTimeFormat("en-US", {
        timeZone: "America/Sao_Paulo",
        weekday: "short",
        hour: "2-digit",
        minute: "2-digit",
        hour12: false,
    }).formatToParts(now);

    const weekdayStr = parts.find(p => p.type === "weekday")?.value || "Mon";
    const hourStr = parts.find(p => p.type === "hour")?.value || "12";
    const minuteStr = parts.find(p => p.type === "minute")?.value || "00";

    const dayMap: Record<string, number> = {
        Sun: 0, Mon: 1, Tue: 2, Wed: 3, Thu: 4, Fri: 5, Sat: 6,
    };
    const dayOfWeek = dayMap[weekdayStr] ?? now.getDay();
    const hourNum = parseInt(hourStr, 10) % 24;
    const timeHHMM = `${String(hourNum).padStart(2, "0")}:${minuteStr}`;

    const greeting = hourNum < 12 ? "Bom dia" : hourNum < 18 ? "Boa tarde" : "Boa noite";
    return { dayOfWeek, timeHHMM, greeting };
}

function isOutsideBusinessHours(cfg: AwayScheduleConfig): { isOutside: boolean; greeting: string } {
    const { dayOfWeek, timeHHMM, greeting } = getNowInSaoPaulo();
    const workDays = Array.isArray(cfg.workDays) ? cfg.workDays : [1, 2, 3, 4, 5];

    if (!workDays.includes(dayOfWeek)) {
        return { isOutside: true, greeting };
    }

    const start = cfg.startTime || "07:30";
    const end = cfg.endTime || "18:00";

    if (timeHHMM < start || timeHHMM > end) {
        return { isOutside: true, greeting };
    }

    return { isOutside: false, greeting };
}

// Helper for permission check
function canAutoReply(config: any, fromMe: boolean, senderJid: string): boolean {
    if (!config || !config.enabled) return false;

    const mode = config.autoReplyMode || 'ALL';

    if (fromMe) {
        if (mode === 'OWNER') return true;
        if (mode === 'ALL') return false;
        return false;
    } else {
        if (mode === 'OWNER') return false;
        if (mode === 'ALL') return true;

        if (mode === 'SPECIFIC') {
            const allowedJids = config.autoReplyAllowedJids || [];
            if (Array.isArray(allowedJids)) {
                return allowedJids.some((jid: string) => senderJid.includes(jid));
            }
        }

        if (mode === 'BLACKLIST') {
            const blockedJids = config.autoReplyBlockedJids || [];
            if (Array.isArray(blockedJids)) {
                const isBlocked = blockedJids.some((jid: string) => senderJid.includes(jid));
                return !isBlocked;
            }
            return true;
        }
    }

    return false;
}

async function sendBotText(sock: WASocket, remoteJid: string, text: string, dbSessionId?: string) {
    let syncedTimestamp: Date | undefined;
    if (dbSessionId && remoteJid) {
        try {
            const latestMsg = await prisma.message.findFirst({
                where: { sessionId: dbSessionId, remoteJid },
                orderBy: { timestamp: "desc" },
                select: { timestamp: true }
            });
            syncedTimestamp = getMonotonicChatTimestamp(latestMsg?.timestamp || null);
        } catch {}
    }
    const sendOptions: any = { skipAntiSpam: true };
    if (syncedTimestamp) sendOptions.timestamp = syncedTimestamp;

    const sent = await sock.sendMessage(remoteJid, { text }, sendOptions);
    if (sent?.key?.id) botSentKeys.add(sent.key.id);
}

async function persistFlowState(
    dbSessionId: string,
    remoteJid: string,
    activeState: ActiveFlowState | null,
    completedAt?: number
) {
    try {
        const contact = await prisma.contact.findFirst({
            where: {
                sessionId: dbSessionId,
                OR: [
                    { jid: remoteJid },
                    { lid: remoteJid },
                    { remoteJidAlt: remoteJid }
                ]
            },
            select: { id: true, data: true }
        });
        if (!contact) return;
        const prevData = (contact.data && typeof contact.data === "object" && !Array.isArray(contact.data))
            ? (contact.data as Record<string, any>)
            : {};
        const prevFlow = (prevData.chatbotFlow && typeof prevData.chatbotFlow === "object") ? prevData.chatbotFlow : {};
        await prisma.contact.update({
            where: { id: contact.id },
            data: {
                data: {
                    ...prevData,
                    chatbotFlow: {
                        active: activeState,
                        completedAt: completedAt ?? prevFlow.completedAt ?? 0,
                    },
                } as any,
            },
        });
    } catch {}
}

async function loadPersistedFlowState(
    dbSessionId: string,
    remoteJid: string
): Promise<{ active: ActiveFlowState | null; completedAt: number }> {
    try {
        const contact = await prisma.contact.findFirst({
            where: {
                sessionId: dbSessionId,
                OR: [
                    { jid: remoteJid },
                    { lid: remoteJid },
                    { remoteJidAlt: remoteJid }
                ]
            },
            select: { data: true }
        });
        const cf = (contact?.data as any)?.chatbotFlow;
        if (cf && typeof cf === "object") {
            return {
                active: cf.active && cf.active.stepId ? cf.active : null,
                completedAt: Number(cf.completedAt || 0),
            };
        }
    } catch {}
    return { active: null, completedAt: 0 };
}

async function assignKanbanLabel(dbSessionId: string, remoteJid: string, labelName?: string) {
    if (!labelName) return;
    try {
        let targetJid = remoteJid;
        if (targetJid.endsWith("@lid")) {
            const bare = targetJid.split("@")[0];
            const c = await prisma.contact.findFirst({
                where: {
                    sessionId: dbSessionId,
                    OR: [{ lid: targetJid }, { jid: targetJid }],
                    AND: [{ OR: [{ jid: { endsWith: "@s.whatsapp.net" } }, { remoteJidAlt: { endsWith: "@s.whatsapp.net" } }] }]
                },
                select: { jid: true, remoteJidAlt: true }
            });
            if (c) {
                targetJid = c.jid.endsWith("@s.whatsapp.net") ? c.jid : (c.remoteJidAlt || targetJid);
            } else {
                const auth = await prisma.authState.findFirst({
                    where: { key: `lid-mapping-${bare}_reverse` },
                    select: { value: true }
                });
                const clean = auth?.value ? String(auth.value).replace(/\D/g, "") : "";
                if (clean) targetJid = `${clean}@s.whatsapp.net`;
            }
        }

        const label = await prisma.label.findUnique({
            where: { sessionId_name: { sessionId: dbSessionId, name: labelName } },
            select: { id: true }
        });
        if (!label) return;
        await prisma.chatLabel.deleteMany({
            where: {
                chatJid: targetJid,
                label: { sessionId: dbSessionId }
            }
        });
        await prisma.chatLabel.create({
            data: {
                labelId: label.id,
                chatJid: targetJid
            }
        });
    } catch {}
}

async function enterFlowStep(
    sock: WASocket,
    sessionId: string,
    dbSessionId: string,
    remoteJid: string,
    flow: ChatbotFlowConfig,
    stepId: string,
    state: ActiveFlowState,
    ctx: { greeting: string; botName: string; pushName: string },
    depth = 0
): Promise<void> {
    if (depth > 8) return; // guard against accidental cycles in "message" steps
    const step = flow.steps.find(s => s.id === stepId);
    if (!step) {
        activeFlowMap.delete(`${sessionId}:${remoteJid}`);
        return;
    }

    state.stepId = step.id;
    state.updatedAt = Date.now();
    if (step.kanbanLabelName) {
        assignKanbanLabel(dbSessionId, remoteJid, step.kanbanLabelName).catch(() => {});
    }

    const msgs = (step.messages || []).filter(m => m && m.trim().length > 0);

    if (step.type === "menu" && step.options && step.options.length > 0) {
        // Filter only enabled options (enabled !== false)
        const activeOptions = step.options.filter(o => o.enabled !== false);
        if (activeOptions.length === 0) {
            logger.warn("AutoReply", `Menu step ${step.id} has no active options`);
        }

        // Send all messages before the last one as normal bubbles, then attach the menu to the last message
        for (let i = 0; i < msgs.length - 1; i++) {
            await sendBotText(sock, remoteJid, applyFlowVariables(msgs[i], state.vars, ctx), dbSessionId);
            await new Promise(r => setTimeout(r, 450));
        }
        const rawPrompt = msgs[msgs.length - 1] || "Escolha uma das opções abaixo:";
        const promptText = applyFlowVariables(rawPrompt, state.vars, ctx);

        let sentList = false;
        if (flow.menuStyle === "list") {
            try {
                let syncedTimestamp: Date | undefined;
                try {
                    const latestMsg = await prisma.message.findFirst({
                        where: { sessionId: dbSessionId, remoteJid },
                        orderBy: { timestamp: "desc" },
                        select: { timestamp: true }
                    });
                    syncedTimestamp = getMonotonicChatTimestamp(latestMsg?.timestamp || null);
                } catch {}
                const listOptions: any = { skipAntiSpam: true };
                if (syncedTimestamp) listOptions.timestamp = syncedTimestamp;

                const sent = await sock.sendMessage(remoteJid, {
                    text: promptText,
                    footer: ctx.botName || "ZapFlow",
                    title: "",
                    buttonText: step.menuButtonText || "Escolher Opções",
                    sections: [
                        {
                            title: "Opções disponíveis",
                            rows: activeOptions.map((opt, idx) => ({
                                rowId: opt.id || `opt_${idx + 1}`,
                                title: opt.title.slice(0, 24),
                                description: (opt.description || "").slice(0, 72),
                            })),
                        },
                    ],
                } as any, listOptions);
                if (sent?.key?.id) botSentKeys.add(sent.key.id);
                sentList = true;
            } catch (err) {
                logger.warn("AutoReply", `Interactive listMessage failed, falling back to numbered menu: ${(err as any)?.message}`);
            }
        }

        if (!sentList) {
            const numberedLines = activeOptions
                .map((opt, idx) => `*${idx + 1}.* ${opt.title}${opt.description ? `\n   _${opt.description}_` : ""}`)
                .join("\n\n");
            await sendBotText(sock, remoteJid, `${promptText}\n\n${numberedLines}\n\n_Responda com o número da opção desejada._`, dbSessionId);
        }

        activeFlowMap.set(`${sessionId}:${remoteJid}`, state);
        persistFlowState(dbSessionId, remoteJid, state).catch(() => {});
        return;
    }

    // Send step text bubbles
    for (let i = 0; i < msgs.length; i++) {
        await sendBotText(sock, remoteJid, applyFlowVariables(msgs[i], state.vars, ctx), dbSessionId);
        if (i < msgs.length - 1) await new Promise(r => setTimeout(r, 450));
    }

    if (step.type === "collect_input") {
        activeFlowMap.set(`${sessionId}:${remoteJid}`, state);
        persistFlowState(dbSessionId, remoteJid, state).catch(() => {});
        return;
    }

    if (step.type === "handoff") {
        const key = `${sessionId}:${remoteJid}`;
        const nowDone = Date.now();
        activeFlowMap.delete(key);
        flowCooldownMap.set(key, nowDone);
        persistFlowState(dbSessionId, remoteJid, null, nowDone).catch(() => {});
        pauseBotForChat(sessionId, remoteJid, step.handoffPauseMinutes || 60);

        // Send alert notification to analyst or team group if configured
        const targetJids: string[] = [];
        if (step.notifyJid) targetJids.push(step.notifyJid);
        if (Array.isArray(step.notifyJids)) {
            for (const jid of step.notifyJids) {
                if (jid && !targetJids.includes(jid)) {
                    targetJids.push(jid);
                }
            }
        }

        if (targetJids.length > 0 && step.notifyMessage) {
            try {
                const alertText = applyFlowVariables(step.notifyMessage, state.vars, ctx);
                for (const destJid of targetJids) {
                    try {
                        await sendBotText(sock, destJid, alertText, dbSessionId);
                        logger.info("AutoReply", `Chatbot notification alert sent to ${destJid}`);
                    } catch (itemErr: any) {
                        logger.warn("AutoReply", `Failed to send alert to ${destJid}: ${itemErr?.message}`);
                    }
                }
            } catch (notifyErr: any) {
                logger.warn("AutoReply", `Failed to send alert batch: ${notifyErr?.message}`);
            }
        }

        try {
            const io = (global as any).io;
            io?.to(sessionId).emit("human.handoff", {
                jid: remoteJid,
                vars: state.vars,
                timestamp: new Date().toISOString(),
            });
        } catch {}
        logger.info("AutoReply", `Chatbot flow completed -> handoff for ${remoteJid}`);
        return;
    }

    if (step.type === "message") {
        if (step.nextStepId) {
            await new Promise(r => setTimeout(r, 450));
            await enterFlowStep(sock, sessionId, dbSessionId, remoteJid, flow, step.nextStepId, state, ctx, depth + 1);
        } else {
            const key = `${sessionId}:${remoteJid}`;
            activeFlowMap.delete(key);
            flowCooldownMap.set(key, Date.now());
        }
    }
}

export async function bindAutoReply(sock: WASocket, sessionId: string) {
    if ((sock as any)._autoReplyBound) return;
    (sock as any)._autoReplyBound = true;
    sock.ev.on('messages.upsert', async ({ messages, type }) => {
        if (type !== 'notify') return;

        // Fetch session ID and Bot Config once per batch (optimization)
        const session = await prisma.session.findUnique({
            where: { sessionId },
            // @ts-ignore
            include: { botConfig: true }
        });

        if (!session) return;

        // @ts-ignore
        let config = (session as any).botConfig;

        if (!config) {
            logger.warn("AutoReply", "No config found, creating default...");
            config = await prisma.botConfig.create({
                data: {
                    sessionId: session.id,
                    enabled: true,
                    botMode: 'OWNER',
                    autoReplyMode: 'ALL'
                }
            });
        }

        if (!config || !config.enabled) return;

        for (const msg of messages) {
            const fromMe = msg.key.fromMe || false;
            const remoteJid = msg.key.remoteJid;

            const isGroup = remoteJid?.endsWith("@g.us") || false;
            const isStatus = remoteJid === "status@broadcast";
            if (isStatus) continue;

            const remoteJidAlt = msg.key.remoteJidAlt;
            let senderJid = (isGroup ? (msg.key.participant || msg.participant) : remoteJid);

            if (!isGroup && remoteJidAlt) {
                senderJid = remoteJidAlt;
            }

            if (!remoteJid || !senderJid) continue;

            // Human handoff: se o operador humano enviou uma mensagem na conversa, pausa o robô por 120min (2h)
            if (fromMe && remoteJid) {
                if (msg.key?.id && botSentKeys.has(msg.key.id)) {
                    botSentKeys.delete(msg.key.id);
                } else if (!isGroup) {
                    pauseBotForChat(sessionId, remoteJid, 120);
                    logger.info("AutoReply", `Atendimento humano ativo: robô pausado por 120 min em ${remoteJid}`);
                }
                continue;
            }

            // Se a conversa estiver temporariamente sob atendimento humano, ignora auto-resposta
            if (remoteJid && isBotPausedForChat(sessionId, remoteJid)) {
                logger.info("AutoReply", `Auto-resposta ignorada para ${remoteJid}: atendimento humano em andamento`);
                continue;
            }

            // Verificação no banco de dados: se um atendente humano respondeu recentemente (últimas 2 horas), não dispara robô
            if (!isGroup && remoteJid) {
                try {
                    const twoHoursAgo = new Date(Date.now() - 2 * 60 * 60 * 1000);
                    const recentHumanMsg = await prisma.message.findFirst({
                        where: {
                            sessionId: session.id,
                            fromMe: true,
                            remoteJid: remoteJid,
                            timestamp: { gte: twoHoursAgo }
                        },
                        orderBy: { timestamp: "desc" },
                        select: { id: true, timestamp: true }
                    });
                    if (recentHumanMsg) {
                        pauseBotForChat(sessionId, remoteJid, 120);
                        logger.info("AutoReply", `Auto-resposta ignorada para ${remoteJid}: atendente humano já conversou recentemente`);
                        continue;
                    }
                } catch (historyErr) {
                    // Fail-safe silencioso
                }
            }

            // Check Permissions
            if (!canAutoReply(config, fromMe, senderJid)) continue;

            const content = normalizeMessageContent(msg.message);
            const selectedRowId =
                (content as any)?.listResponseMessage?.singleSelectReply?.selectedRowId ||
                (content as any)?.buttonsResponseMessage?.selectedButtonId ||
                "";
            const selectedTitle =
                (content as any)?.listResponseMessage?.title ||
                (content as any)?.buttonsResponseMessage?.selectedDisplayText ||
                "";
            const text =
                content?.conversation ||
                content?.extendedTextMessage?.text ||
                content?.imageMessage?.caption ||
                content?.videoMessage?.caption ||
                selectedTitle ||
                "";

            // Intelligent Human Handoff: se o cliente solicitar atendimento humano, pausa o robô por 60min
            const cleanTextNorm = text.toLowerCase().trim();
            const HANDOFF_KEYWORDS = ["atendente", "falar com atendente", "humano", "falar com humano", "suporte humano", "atendimento humano", "pessoa real", "operador"];
            const isHandoffRequest = !isGroup && HANDOFF_KEYWORDS.some(kw => cleanTextNorm === kw || cleanTextNorm.startsWith(kw + " ") || cleanTextNorm.endsWith(" " + kw));
            if (isHandoffRequest && remoteJid) {
                pauseBotForChat(sessionId, remoteJid, 60);
                logger.info("AutoReply", `Transbordo humano solicitado por ${remoteJid}: robô pausado por 60 min.`);
                try {
                    const io = (global as any).io;
                    io?.to(sessionId).emit("human.handoff", {
                        jid: remoteJid,
                        text,
                        timestamp: new Date().toISOString()
                    });
                } catch {}
                try {
                    await sock.sendMessage(remoteJid, {
                        text: "Entendido! Estou transferindo seu atendimento para nossa equipe humana. Um momento, por favor!"
                    });
                } catch {}
                continue;
            }

            try {
                // Fetch rules for this session
                const allRules = await prisma.autoReply.findMany({
                    where: {
                        session: {
                            sessionId: sessionId
                        }
                    }
                });

                const awayRule = allRules.find(r => r.keyword === AWAY_SCHEDULE_KEYWORD);
                const flowRule = allRules.find(r => r.keyword === CHATBOT_FLOW_KEYWORD);
                const keywordRules = allRules.filter(
                    r => r.keyword !== AWAY_SCHEDULE_KEYWORD && r.keyword !== CHATBOT_FLOW_KEYWORD
                );

                // ─── Chatbot Multi-Step Flow Execution (1-on-1 chats) ───
                if (!isGroup && flowRule?.response) {
                    try {
                        const flowCfg: ChatbotFlowConfig = JSON.parse(flowRule.response);
                        if (flowCfg.enabled && Array.isArray(flowCfg.steps) && flowCfg.steps.length > 0) {
                            const flowKey = `${sessionId}:${remoteJid}`;
                            const { greeting } = getNowInSaoPaulo();
                            const ctx = {
                                greeting,
                                botName: config.botName || "ZapFlow",
                                pushName: msg.pushName || "",
                            };

                            let activeState = activeFlowMap.get(flowKey);
                            let persistedCompletedAt = flowCooldownMap.get(flowKey) || 0;
                            if (!activeState && !persistedCompletedAt) {
                                const persisted = await loadPersistedFlowState(session.id, remoteJid);
                                if (persisted.active) {
                                    activeState = persisted.active;
                                    activeFlowMap.set(flowKey, activeState);
                                }
                                if (persisted.completedAt > 0) {
                                    persistedCompletedAt = persisted.completedAt;
                                    flowCooldownMap.set(flowKey, persistedCompletedAt);
                                }
                            }
                            const timeoutMs = (flowCfg.stepTimeoutMinutes || 30) * 60 * 1000;
                            if (activeState && Date.now() - activeState.updatedAt > timeoutMs) {
                                activeFlowMap.delete(flowKey);
                                persistFlowState(session.id, remoteJid, null).catch(() => {});
                                activeState = undefined;
                            }

                            if (activeState) {
                                const currentStep = flowCfg.steps.find(s => s.id === activeState!.stepId);
                                if (currentStep?.type === "collect_input") {
                                    const userReply = text.trim();
                                    if (userReply) {
                                        if (currentStep.saveToVar) {
                                            if (currentStep.saveToVar === "nome_cliente") {
                                                const wordCount = userReply.split(/\s+/).length;
                                                const looksLikeIntent = wordCount >= 3 || /\b(quero|preciso|gostaria|alugar|aluguel|comprar|compra|vender|venda|casa|apartamento|imovel|imóvel|terreno|construir|reforma|reformar|projeto|moveis|móveis|orcamento|orçamento|valor|preco|preço|atendimento|oi|ola|olá|bom dia|boa tarde|boa noite)\b/i.test(userReply);
                                                if (looksLikeIntent) {
                                                    const profileFirst = (ctx.pushName || "").trim().split(/\s+/)[0];
                                                    activeState.vars.nome_cliente = profileFirst && profileFirst.length >= 2 ? profileFirst : "cliente";
                                                    activeState.vars.assunto_inicial = userReply;
                                                } else {
                                                    activeState.vars.nome_cliente = userReply;
                                                    if (userReply.length >= 2 && userReply.length <= 60) {
                                                        prisma.contact.updateMany({
                                                            where: { sessionId: session.id, jid: remoteJid },
                                                            data: { name: userReply }
                                                        }).catch(() => {});
                                                    }
                                                }
                                            } else {
                                                activeState.vars[currentStep.saveToVar] = userReply;
                                            }
                                        }
                                        if (currentStep.nextStepId) {
                                            await enterFlowStep(sock, sessionId, session.id, remoteJid, flowCfg, currentStep.nextStepId, activeState, ctx);
                                        } else {
                                            activeFlowMap.delete(flowKey);
                                            flowCooldownMap.set(flowKey, Date.now());
                                            persistFlowState(session.id, remoteJid, null, Date.now()).catch(() => {});
                                        }
                                        continue;
                                    }
                                } else if (currentStep?.type === "menu" && currentStep.options?.length) {
                                    const activeOptions = currentStep.options.filter(o => o.enabled !== false);
                                    const normalizedReply = text.trim().toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
                                    let chosen = activeOptions.find(
                                        (o, idx) => {
                                            const normTitle = o.title.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
                                            if (selectedRowId && o.id === selectedRowId) return true;
                                            if (normalizedReply === String(idx + 1)) return true;
                                            if (normalizedReply === normTitle) return true;
                                            if (normalizedReply.length >= 3 && normTitle.includes(normalizedReply)) return true;
                                            const replyWords = normalizedReply.split(/\s+/).filter((w: string) => w.length >= 4);
                                            return replyWords.some((w: string) => normTitle.includes(w));
                                        }
                                    );
                                    if (!chosen && (normalizedReply.includes("primeira vez") || normalizedReply.includes("primeiro contato"))) {
                                        chosen = activeOptions.find(o => o.id === "opt_new") || activeOptions[1];
                                    }
                                    if (!chosen && (normalizedReply.includes("ja sou") || normalizedReply.includes("sou cliente"))) {
                                        chosen = activeOptions.find(o => o.id === "opt_existing") || activeOptions[0];
                                    }
                                    if (chosen) {
                                        if (currentStep.saveToVar) {
                                            activeState.vars[currentStep.saveToVar] = chosen.title;
                                        }
                                        if (chosen.nextStepId) {
                                            await enterFlowStep(sock, sessionId, session.id, remoteJid, flowCfg, chosen.nextStepId, activeState, ctx);
                                        } else {
                                            activeFlowMap.delete(flowKey);
                                            flowCooldownMap.set(flowKey, Date.now());
                                        }
                                        continue;
                                    } else if (text.trim()) {
                                        await sendBotText(
                                            sock,
                                            remoteJid,
                                            `Por favor, escolha uma opção válida (digite de *1* a *${activeOptions.length}* ou toque no botão *${currentStep.menuButtonText || "Escolher Opções"}*).`,
                                            session.id
                                        );
                                        continue;
                                    }
                                }
                            } else {
                                // Check if we should start the flow
                                const lastCompleted = persistedCompletedAt || flowCooldownMap.get(flowKey) || 0;
                                const cooldownMs = (flowCfg.cooldownHours ?? 24) * 60 * 60 * 1000;
                                const inCooldown = cooldownMs > 0 && Date.now() - lastCompleted < cooldownMs;
                                const incomingLower = text.trim().toLowerCase();
                                const matchesTrigger =
                                    flowCfg.triggerMode === "ALWAYS_WHEN_IDLE" ||
                                    (flowCfg.triggerMode === "KEYWORD" &&
                                        Array.isArray(flowCfg.triggerKeywords) &&
                                        flowCfg.triggerKeywords.some(kw => incomingLower === kw.toLowerCase() || incomingLower.includes(kw.toLowerCase())));

                                if (!inCooldown && matchesTrigger && (text.trim() || msg.message)) {
                                    const newState: ActiveFlowState = {
                                        stepId: flowCfg.startStepId,
                                        vars: {},
                                        updatedAt: Date.now(),
                                    };
                                    await enterFlowStep(sock, sessionId, session.id, remoteJid, flowCfg, flowCfg.startStepId, newState, ctx);
                                    continue;
                                }
                            }
                        }
                    } catch (flowErr) {
                        logger.error("AutoReply", "Error running chatbot flow", flowErr);
                    }
                }

                let keywordMatched = false;

                if (text) {
                    for (const rule of keywordRules) {
                        let match = false;
                        const keyword = rule.keyword.toLowerCase();
                        const incoming = text.toLowerCase();

                        switch (rule.matchType) {
                            case 'EXACT':
                                match = incoming === keyword;
                                break;
                            case 'CONTAINS':
                                match = incoming.includes(keyword);
                                break;
                            case 'STARTS_WITH':
                                match = incoming.startsWith(keyword);
                                break;
                            case 'REGEX':
                                try {
                                    const regex = new RegExp(rule.keyword, 'i');
                                    match = regex.test(text);
                                } catch (e) {
                                    logger.error("AutoReply", "Invalid regex in auto-reply", rule.keyword);
                                }
                                break;
                        }

                        if (match) {
                            const triggerType = (rule as any).triggerType || 'ALL';

                            if (triggerType === 'GROUP' && !isGroup) continue;
                            if (triggerType === 'PRIVATE' && isGroup) continue;

                            logger.info("AutoReply", `Match: ${rule.keyword} -> ${remoteJid}`);
                            keywordMatched = true;

                            if (rule.isMedia && rule.mediaUrl) {
                                const url = rule.mediaUrl;
                                const type = (rule as any).mediaType || "document";
                                
                                let payload: any = {};
                                if (rule.response) {
                                    payload.caption = rule.response;
                                }

                                if (type === "image") {
                                    payload.image = { url };
                                } else if (type === "video") {
                                    payload.video = { url };
                                } else if (type === "audio") {
                                    payload = { audio: { url } };
                                } else {
                                    payload.document = { url };
                                    payload.mimetype = 'application/octet-stream';
                                    payload.fileName = url.split('/').pop() || 'document';
                                }
                                
                                try {
                                    const sent = await sock.sendMessage(remoteJid, payload, { quoted: msg });
                                    if (sent?.key?.id) botSentKeys.add(sent.key.id);
                                } catch (err: any) {
                                    logger.error("AutoReply", `Failed to send media auto-reply from URL: ${err.message}. Falling back to text.`);
                                    if (rule.response) {
                                        const fallbackSent = await sock.sendMessage(remoteJid, { text: rule.response }, { quoted: msg });
                                        if (fallbackSent?.key?.id) botSentKeys.add(fallbackSent.key.id);
                                    }
                                }
                            } else if (rule.response) {
                                const sent = await sock.sendMessage(remoteJid, { text: rule.response }, { quoted: msg });
                                if (sent?.key?.id) botSentKeys.add(sent.key.id);
                            }

                            break;
                        }
                    }
                }

                // Out-of-hours / Away Schedule Check (#14) — only for incoming private messages when no keyword matched
                if (!keywordMatched && !fromMe && !isGroup && awayRule?.response) {
                    try {
                        const awayCfg: AwayScheduleConfig = JSON.parse(awayRule.response);
                        if (awayCfg.enabled && awayCfg.message?.trim()) {
                            const { isOutside, greeting } = isOutsideBusinessHours(awayCfg);
                            if (isOutside) {
                                const cooldownKey = `${sessionId}:${remoteJid}`;
                                const lastSent = awayCooldownMap.get(cooldownKey) || 0;
                                const cooldownMs = (awayCfg.cooldownMinutes || 120) * 60 * 1000;
                                const nowMs = Date.now();

                                if (nowMs - lastSent >= cooldownMs) {
                                    awayCooldownMap.set(cooldownKey, nowMs);
                                    const pushName = msg.pushName || "";
                                    const firstName = pushName.trim().split(/\s+/)[0] || "";
                                    const finalMessage = awayCfg.message
                                        .replace(/\{saudacao\}/gi, greeting)
                                        .replace(/\{nome\}/gi, pushName || "cliente")
                                        .replace(/\{primeiro_nome\}/gi, firstName || "cliente");

                                    const awaySent = await sock.sendMessage(remoteJid, { text: finalMessage }, { quoted: msg });
                                    if (awaySent?.key?.id) botSentKeys.add(awaySent.key.id);
                                    logger.info("AutoReply", `Sent out-of-hours away message to ${remoteJid}`);
                                }
                            }
                        }
                    } catch (err) {
                        logger.error("AutoReply", "Failed to parse or execute away schedule config", err);
                    }
                }

                // ─── Welcome Message Check (First Contact / Daily Welcome) ───
                if (!keywordMatched && !fromMe && !isGroup && config?.welcomeMessage?.trim()) {
                    try {
                        const welcomeKey = `welcome:${sessionId}:${remoteJid}`;
                        const lastSent = awayCooldownMap.get(welcomeKey) || 0;
                        const cooldownMs = 24 * 60 * 60 * 1000; // 24 horas por contato
                        const nowMs = Date.now();

                        if (nowMs - lastSent >= cooldownMs) {
                            awayCooldownMap.set(welcomeKey, nowMs);
                            const { greeting } = getNowInSaoPaulo();
                            const pushName = msg.pushName || "";
                            const firstName = pushName.trim().split(/\s+/)[0] || "";
                            const botName = config.botName || "ZapFlow";

                            const finalWelcome = config.welcomeMessage
                                .replace(/\{saudacao\}/gi, greeting)
                                .replace(/\{nome\}/gi, firstName || pushName || "cliente")
                                .replace(/\{primeiro_nome\}/gi, firstName || "cliente")
                                .replace(/\{nome_completo\}/gi, pushName || "cliente")
                                .replace(/\{empresa\}/gi, botName);

                            const welcomeSent = await sock.sendMessage(remoteJid, { text: finalWelcome }, { quoted: msg });
                            if (welcomeSent?.key?.id) botSentKeys.add(welcomeSent.key.id);
                            logger.info("AutoReply", `Sent automated welcome message to ${remoteJid}`);
                        }
                    } catch (welcomeErr) {
                        logger.error("AutoReply", "Failed to send welcome message", welcomeErr);
                    }
                }

            } catch (e) {
                logger.error("AutoReply", "Error executing auto-reply", e);
            }
        }
    });
}
